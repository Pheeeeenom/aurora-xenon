#!/usr/bin/env python3
"""Build a game's shader pack for the vulkan4xenon backend (include/aurora/glsl_pack.h) from the GLSL a run on the null
backend recorded (AURORA_GLSL_RECORD_DIR): each program compiled to SPIR-V with glslang and to Xenos microcode with
xost, through vulkan4xenon's tools/build_shaders.py. Writes a C source and header holding aurora_glsl_pack, which finds
each program's SPIR-V by its source's hash, and v4x_shader_bundle, which the layer finds the microcode in.

    build_glsl_pack.py --vulkan4xenon ../vulkan4xenon --xost ../Xbox-360-SDK/xenos-toolchain \
        --output platforms/xenon/glsl_pack platforms/xenon/shaders

--optimize has xost rewrite each program's instructions first (xost:xasm/optimize.py), as the Xbox 360's pixel
shading is most of a frame's GPU time.

A program glslang or xost refuses, as xost does one past its kind's share of xsdk's registers, is left out and listed;
the backend then logs it as missing and skips its draws. Run it from the game's repository root, as build_shaders.py
wants paths relative.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

# A recorded program's name: its hash (glsl::program_hash) in 16 hex digits, and its stage.
PROGRAM_NAME = re.compile(r"^([0-9a-f]{16})\.(vert|frag)$")
C_PREFIX = "glsl_"


def compile_spirv(glslang, source, directory):
    """The program's SPIR-V, or the reason glslang refused it."""
    output = Path(os.path.relpath(directory)) / (source.name + ".spv")
    result = subprocess.run([str(glslang), "-V", str(source), "-o", str(output)], capture_output=True, text=True)
    if result.returncode != 0:
        return None, "glslang: " + (result.stdout + result.stderr).strip()
    return output.read_bytes(), None


def lower(build_shaders, xost, spirv_bytes, source, optimize):
    """build_shaders.lower's result, or the reason xost refused the program."""
    try:
        container, literals, resources = build_shaders.lower(xost, spirv_bytes, source, optimize)
    except (Exception, SystemExit) as error:  # xost raises its own errors, and build_shaders exits
        return None, f"xost: {type(error).__name__}: {error}"
    return (container, literals, resources), None


def write_pack(output, shaders, recorded, left_out, optimize):
    """Puts aurora_glsl_pack after the bundle build_shaders.py wrote, and says what made both."""
    generated = (f"// Generated by Aurora's tools/build_glsl_pack.py{' --optimize' if optimize else ''} from "
                 f"{len(shaders)} of {recorded} recorded programs; don't edit.")
    header = output.with_suffix(".h")
    lines = header.read_text().split("\n")
    header.write_text("\n".join([generated] + lines[1:]), newline="\n")
    source = output.with_suffix(".c")
    lines = source.read_text().split("\n")
    lines = [generated] + [f"// Left out: {name}: {reason.splitlines()[0]}" for name, reason in left_out] + lines[1:]
    lines.insert(lines.index('#include "vulkan4xenon.h"'), "#include <aurora/glsl_pack.h>")
    lines[-1:] = ["", "static const AuroraGlslProgram programs[] = {"]
    for shader in sorted(shaders, key=lambda s: s["program"]):
        lines.append(f"\t{{ 0x{shader['program']:016X}ull, {shader['name']}_spirv, {len(shader['spirv'])} }},")
    lines += ["};", "", f"const AuroraGlslPack aurora_glsl_pack = {{ programs, {len(shaders)} }};", ""]
    source.write_text("\n".join(lines), newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--vulkan4xenon", type=Path, required=True, help="vulkan4xenon's repository")
    parser.add_argument("--xost", type=Path, required=True, help="xost's repository (xenos-toolchain)")
    parser.add_argument("--glslang", type=Path, help="glslang, by default xost's tools/glslang/bin/glslang.exe")
    parser.add_argument("--output", type=Path, required=True, help="the C source and header to write, less suffix")
    parser.add_argument("--optimize", action="store_true", help="have xost rewrite each program's instructions first")
    parser.add_argument("recorded", type=Path, help="the directory the null backend recorded into")
    args = parser.parse_args()
    sys.path.insert(0, str(args.vulkan4xenon / "tools"))
    import build_shaders

    glslang = args.glslang or args.xost / "tools" / "glslang" / "bin" / "glslang.exe"
    sources = sorted(path for path in args.recorded.iterdir() if PROGRAM_NAME.match(path.name))
    shaders = []
    left_out = []
    # Under build/, so the SPIR-V's path is relative too.
    Path("build").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir="build") as directory:
        for source in sources:
            spirv_bytes, reason = compile_spirv(glslang, source, directory)
            if spirv_bytes is not None:
                lowered, reason = lower(build_shaders, args.xost.resolve(), spirv_bytes, source, args.optimize)
            if reason:
                left_out.append((source.name, reason))
                print(f"left out {source.name}: {reason}")
                continue
            container, literals, resources = lowered
            shaders.append({"name": build_shaders.c_name(source, C_PREFIX), "spirv": spirv_bytes,
                            "hash": build_shaders.fnv1a_64(spirv_bytes), "container": container,
                            "literals": literals, "resources": resources,
                            "program": int(PROGRAM_NAME.match(source.name).group(1), 16)})
    build_shaders.write_outputs(args.output, shaders, [s["name"] for s in shaders], build_shaders.DEFAULT_BUNDLE)
    write_pack(args.output, shaders, len(sources), left_out, args.optimize)
    print(f"{len(shaders)} of {len(sources)} programs packed into {args.output.with_suffix('.c')}")


if __name__ == "__main__":
    main()
